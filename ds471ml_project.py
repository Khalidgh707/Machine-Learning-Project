"""## Stage 3: Model Selection and Development
The target is a continuous number, so we use **regression** models. We build three:
* Linear Regression (Ridge)
* Random Forest Regressor
* Neural Network (MLP, mandatory)
"""

from sklearn.linear_model import LinearRegression, Ridge
from sklearn.model_selection import GridSearchCV
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

def reg_metrics(y_true, y_pred):
    mse = mean_squared_error(y_true, y_pred)
    return {"MAE": mean_absolute_error(y_true, y_pred), "MSE": mse,
            "RMSE": np.sqrt(mse), "R2": r2_score(y_true, y_pred)}

